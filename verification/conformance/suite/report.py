"""Generate verification/COVERAGE.md from executed evidence."""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from .requirements import (MACHINE_CHECKED_UNIVERSAL, compute_statuses,
                           load_requirements)

BT = chr(96)


def _status_cell(status):
    return {
        "verified": "verified",
        "corpus-verified": "corpus-verified",
        "partial": "partial",
        "uncovered": "**uncovered**",
        "not-applicable": "n/a",
        "blocked": "blocked",
    }.get(status, status)


def _code(text):
    return BT + text + BT


def write_report(path: Path, evidence, root: Path):
    requirements = load_requirements(
        root / "verification" / "spec" / "requirements.yaml")
    statuses = compute_statuses(evidence, requirements)
    by_suite = defaultdict(lambda: {"pass": 0, "fail": 0, "skip": 0,
                                    "blocked": 0})
    for result in evidence["results"]:
        by_suite[result["suite"]][result["status"]] += 1

    lines = []
    lines.append("# C4 assignment-conformance coverage")
    lines.append("")
    lines.append("Generated by " + _code(
        "python3 verification/conformance/run_conformance.py") +
        " from the executed results in")
    lines.append(_code(evidence.get(
        "evidence_path",
        "verification/conformance/results/evidence.json")) + ".")
    provenance = evidence.get("provenance", {})
    binary = provenance.get("c4_binary", {})
    if binary:
        lines.append("Compiler binary " + _code(binary.get("path", "?")) +
                     " (sha256 " + _code(binary.get("sha256", "?")) +
                     ", size " + str(binary.get("size", "?")) +
                     ", mtime " + _code(binary.get("mtime", "?")) + ").")
        if binary.get("stale"):
            lines.append("**Warning:** this binary is older than " +
                         _code(str(binary.get("newest_source"))) +
                         "; it was not rebuilt for the recorded source "
                         "revision.")
    lines.append("Source revision " +
                 _code(provenance.get("source_revision",
                                      evidence.get("c4_commit", "unknown"))) +
                 "; verification-suite revision " +
                 _code(provenance.get("verification_revision", "unknown")) +
                 " (conformance tree " +
                 _code(provenance.get("conformance_revision", "unknown")) +
                 "; verification tree " +
                 ("dirty" if provenance.get("verification_dirty")
                  else "clean") + "; working tree " +
                 ("dirty" if evidence.get("working_tree_dirty")
                  else "clean") + " at run time).")
    if provenance.get("command"):
        lines.append("Command: " + _code(provenance["command"]) + ".")
    lines.append("")
    lines.append("This report is evidence on the corpus actually executed. "
                 "A passing case is not a proof for untested inputs.")
    lines.append("")
    lines.append("Status policy:")
    lines.append("")
    if MACHINE_CHECKED_UNIVERSAL:
        lines.append("- **verified**: a machine-checked universal claim (%s)."
                     % ", ".join(sorted(MACHINE_CHECKED_UNIVERSAL)))
    else:
        lines.append("- **verified**: a machine-checked universal claim. No "
                     "requirement currently has one.")
    lines.append("- **corpus-verified**: every mapped case passed, so the "
                 "finite corpus conforms; this is not a universal proof.")
    lines.append("- **partial**: at least one mapped case failed or was "
                 "skipped; the detail records the counts.")
    lines.append("- **blocked**: a mapped check could not be executed; the "
                 "detail records it.")
    lines.append("- **uncovered**: no conformance case is mapped.")
    lines.append("- **n/a**: the requirement is explicitly out of scope.")
    lines.append("")
    lines.append("## Result summary")
    lines.append("")
    lines.append("| suite | pass | fail | skip | blocked |")
    lines.append("|---|---:|---:|---:|---:|")
    for suite in evidence["suites"]:
        entry = by_suite.get(suite, {"pass": 0, "fail": 0, "skip": 0,
                                     "blocked": 0})
        lines.append("| %s | %d | %d | %d | %d |"
                     % (suite, entry["pass"], entry["fail"], entry["skip"],
                        entry["blocked"]))
    summary = evidence["summary"]
    lines.append("| **total** | **%d** | **%d** | **%d** | **%d** |"
                 % (summary["passed"], summary["failed"],
                    summary["skipped"], summary.get("blocked", 0)))
    lines.append("")
    failures = [r for r in evidence["results"] if r["status"] == "fail"]
    lines.append("## Failures")
    lines.append("")
    if not failures:
        lines.append("None in this run.")
    else:
        for result in failures:
            lines.append("- " + _code(result["suite"] + "/" + result["case"]) +
                         ": " + result["detail"].replace("|", "\\|"))
    lines.append("")
    blocked_cases = [r for r in evidence["results"]
                     if r["status"] == "blocked"]
    lines.append("## Blocked checks")
    lines.append("")
    if not blocked_cases:
        lines.append("None in this run.")
    else:
        for result in blocked_cases:
            lines.append("- " + _code(result["suite"] + "/" + result["case"]) +
                         ": " + result["detail"].replace("|", "\\|"))
    lines.append("")
    counts = defaultdict(int)
    for status, _ in statuses.values():
        counts[status] += 1
    lines.append("## Status summary")
    lines.append("")
    lines.append("| status | requirements |")
    lines.append("|---|---:|")
    for status in ("verified", "corpus-verified", "partial", "blocked",
                   "uncovered", "not-applicable"):
        lines.append("| %s | %d |" % (_status_cell(status), counts[status]))
    lines.append("")
    lines.append("## Requirement matrix")
    lines.append("")
    lines.append("| id | classification | status | evidence |")
    lines.append("|---|---|---|---|")
    for requirement in requirements:
        identifier = requirement["id"]
        status = statuses[identifier][0]
        detail = statuses[identifier][1]
        if requirement.get("classification") == "out-of-scope":
            detail = "not an assignment requirement; excluded from scope"
        lines.append("| %s | %s | %s | %s |"
                     % (identifier, requirement.get("classification", ""),
                        _status_cell(status),
                        detail.replace("|", "\\|")))
    lines.append("")
    lines.append("## Uncovered, partial, and blocked requirements")
    lines.append("")
    uncovered = [r["id"] for r in requirements
                 if statuses[r["id"]][0] == "uncovered"]
    partial = [r["id"] for r in requirements
               if statuses[r["id"]][0] == "partial"]
    blocked = [r["id"] for r in requirements
               if statuses[r["id"]][0] == "blocked"]
    lines.append("- uncovered: %s" % (", ".join(uncovered) or "none"))
    lines.append("- partial: %s" % (", ".join(partial) or "none"))
    lines.append("- blocked: %s" % (", ".join(blocked) or "none"))
    lines.append("")
    lines.append("## Grammar production coverage")
    lines.append("")
    coverage = evidence.get("grammar_coverage")
    if not coverage:
        lines.append("No grammar-coverage record was produced by this run.")
    else:
        lines.append(
            "Positive examples exercise %d of %d tracked grammar "
            "alternatives (parser/grammar-* cases)."
            % (coverage["covered"], coverage["alternatives"]))
        uncovered_grammar = coverage.get("uncovered", [])
        if uncovered_grammar:
            lines.append("")
            lines.append("Uncovered alternatives:")
            lines.append("")
            notes = coverage.get("uncovered_notes", {})
            for key in uncovered_grammar:
                note = notes.get(key)
                lines.append("- " + _code(key) +
                             (": " + note if note else ""))
        else:
            lines.append("")
            lines.append("No tracked alternative is uncovered.")
    lines.append("")
    lines.append("## Scope and limitations")
    lines.append("")
    lines.append("- The reference frontend in " + _code(
        "verification/conformance/c4ref") +
        " is an independent executable model derived from the")
    lines.append("  specification; agreement between it and " + _code("src/") +
                 " is conformance evidence, not a refinement proof.")
    lines.append("- Differential execution uses defined programs only and "
                 "does not model undefined behavior, evaluation order,")
    lines.append("  implementation-defined " + _code("char") +
                 " signedness, or struct padding beyond the fixtures.")
    lines.append("- LLVM 23.1.5 is used; compatibility with the assignment's "
                 "LLVM 15.0 is not claimed (F-009).")
    lines.append("- Alive2, general SCCP refinement proofs, LLVM operational "
                 "semantics, and C++ implementation-refinement proofs are")
    lines.append("  explicitly out of scope.")
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
